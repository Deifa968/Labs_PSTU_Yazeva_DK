/*Задача 2. Дан одномерный массив целых чисел, проверить, упорядочен ли он по возрастанию.
Решить с флажком F типа bool, начальное значение false, лучше циклом while.
Цикл завершается, когда перебраны все элементы или найдено нарушение, то есть соседние элементы со знаком >= (тогда F = true и проверка прекращается).
Если ни одно сравнение не нарушило знак «меньше», вывести сообщение, что массив упорядочен.*/
#include <iostream>
#include <clocale>
using namespace std;
int main()
{
    setlocale(LC_ALL, "RU");
    bool f = false;
    int m[10] = { 2,8,26,49,52,67,68,69,87,99 }, i = 0, a, b;
    while ((!f) && (i < 10 - 1))
    {
        a = m[i];
        b = m[i + 1];
        if (a >= b) f = true;
        i += 1;
    }
    if (f) cout << "последовательность не упорядочена";
    else cout << "последовательность упорядочена";
    return 0;
}